package dev.client.plugin.tiktok

/**
 * Настройки провайдера.
 *
 * Меняются не из клиента, а выпуском новой версии плагина: в этой архитектуре
 * version в sources.json обновляется без релиза приложения, так что это дёшево.
 * Добавлять метод configure() в ProviderContext пришлось бы через общий контракт,
 * а его версионирует сторона клиента — не наша.
 */
internal data class TikTokConfig(
    val userAgent: String = DEFAULT_USER_AGENT,
    val region: String = "US",
    val language: String = "en",
    val baseUrl: String = "https://www.tiktok.com",
    /**
     * Раздел `/embed` — часть сайта TikTok, которая отдаёт данные обычным HTML
     * без подписи `X-Bogus`/`X-Gnarly`: профиль, видео, страница хештега.
     */
    val embedPath: String = "/embed",
    /**
     * Публичный шлюз, у которого есть лента: у самого TikTok она закрыта
     * подписью браузерного SDK, а `/embed` её не отдаёт.
     */
    val gatewayUrl: String = "https://www.tikwm.com",
    /**
     * Официальная лента TikTok. Работает только с подписью `X-Gnarly` и cookie
     * вошедшего аккаунта; без cookie отвечает пустым списком, и тогда лента
     * берётся из шлюза — см. [TikTokApi.feed].
     */
    val recommendPath: String = "/api/recommend/item_list/",
    /**
     * Ключ в хранилище плагина, под которым лежит строка `Cookie` вошедшего
     * аккаунта. Плагин читает её и ставит заголовок сам. Сюда же он кладёт
     * строку, полученную через [sessionImportUrl], — тогда она переживает
     * перезапуск приложения.
     *
     * Клиент этот ключ не трогает: он вообще не участвует в работе с сессией.
     */
    val sessionStorageKey: String = "cookies:www.tiktok.com",

    /**
     * Ключ в хранилище плагина, которым клиент закрепляет источник ленты.
     *
     * - нет значения или любое другое — как обычно: официальная лента, а если сессии нет или она
     *   пуста, шлюз;
     * - `gateway` — только шлюз, даже когда сессия есть;
     * - `official` — снова пробовать официальную ленту, даже если раньше от неё отказались.
     *
     * Нужен клиенту, чтобы сравнивать источники (например, как они отвечают из разных регионов).
     */
    val feedSourceStorageKey: String = "settings:feed_source",

    /**
     * Ссылка, по которой плагин забирает строку `Cookie` вошедшего аккаунта.
     *
     * Нужна там, где в приложении негде войти: клиент заморожен, экрана входа
     * нет, а `WebView` на `tiktok.com` не открывается — значит банка процесса
     * пуста. Тогда единственный канал до плагина — сеть: пользователь кладёт
     * строку по своему адресу, плагин забирает её один раз и запоминает.
     *
     * Пока строка задана, она запрашивается при каждом запуске: так сессия
     * обновляется без нового релиза плагина. Удалили ссылку — плагин остаётся
     * на том, что успел сохранить.
     *
     * Пустая строка — импорт выключен (по умолчанию). Значение задаётся
     * выпуском новой версии плагина, а не настройкой в приложении.
     *
     * Это чужая сессия: кто знает ссылку, тот забирает строку. Поэтому адрес
     * должен быть свой, а после того как всё заработало — удалён.
     */
    val sessionImportUrl: String = "",
    /** Сколько элементов просить за раз: шлюз больше 30 не отдаёт. */
    val feedPageSize: Int = 20,
    val commentPageSize: Int = 20,
    /**
     * Поисковик, через индекс которого ищется текст: поиск самого TikTok закрыт
     * подписью, поэтому слова ищутся по проиндексированным страницам видео.
     */
    val searchEngineUrl: String = "https://lite.duckduckgo.com",
    val searchSite: String = "tiktok.com/video",
    /** Сколько найденных видео доразбирать: каждое — отдельный запрос страницы. */
    val searchDetailLimit: Int = 5,
    /** Дополнительные заголовки, если понадобятся конкретной версии эндпоинтов. */
    val extraHeaders: Map<String, String> = emptyMap(),
) {
    companion object {
        const val DEFAULT_USER_AGENT =
            "Mozilla/5.0 (Linux; Android 13; Pixel 7) AppleWebKit/537.36 " +
                "(KHTML, like Gecko) Chrome/126.0.0.0 Mobile Safari/537.36"
    }
}
